#!/usr/bin/env node
// Builds docs/history.md from docs/history/pr-*.md (one file per merged PR) and
// docs/history/topics.json (the phases and topics, in order). Run with `npm run history`.
// `--check` exits with an error instead of writing when docs/history.md is out of date.
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "docs/history";
const out = "docs/history.md";
const repo = "https://github.com/heynewton/newton";
const board = "https://github.com/orgs/heynewton/projects/1/views/4";

const topics = JSON.parse(readFileSync(join(dir, "topics.json"), "utf8"));
const known = new Set(topics.map((t) => `${t.phase}\u0000${t.topic}`));

// When a file has no `merged:` line, use the time it first landed on this branch: with squash
// merges that is the PR's merge time.
function firstCommitted(path) {
  const iso = execFileSync("git", ["log", "--diff-filter=A", "--format=%cI", "--", path], {
    encoding: "utf8",
  })
    .trim()
    .split("\n")
    .pop();
  if (!iso) throw new Error(`${path}: no merged: line and not committed yet`);
  return new Date(iso).toISOString();
}

function read(file) {
  const path = join(dir, file);
  const fields = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    if (!line.trim()) continue;
    const m = /^([a-z]+):\s*(.*)$/.exec(line);
    if (!m) throw new Error(`${path}: can't read line "${line}"`);
    fields[m[1]] = m[2];
  }
  for (const key of ["pr", "phase", "topic", "summary"]) {
    if (!fields[key]) throw new Error(`${path}: missing ${key}:`);
  }
  if (!known.has(`${fields.phase}\u0000${fields.topic}`)) {
    const list = topics.map((t) => `"${t.phase}" / "${t.topic}"`).join(", ");
    throw new Error(`${path}: unknown phase/topic "${fields.phase}" / "${fields.topic}". Use one of ${list}, or add it to topics.json`);
  }
  return {
    pr: Number(fields.pr),
    merged: fields.merged || firstCommitted(path),
    phase: fields.phase,
    topic: fields.topic,
    closes: (fields.closes || "").split(",").map((s) => s.trim()).filter(Boolean),
    summary: fields.summary,
  };
}

const entries = readdirSync(dir)
  .filter((f) => /^pr-\d+\.md$/.test(f))
  .map(read)
  .sort((a, b) => a.merged.localeCompare(b.merged) || a.pr - b.pr);

const line = (e) => {
  const closes = e.closes.length
    ? ` · closes ${e.closes.map((n) => `[#${n}](${repo}/issues/${n})`).join(", ")}`
    : "";
  return `- [#${e.pr}](${repo}/pull/${e.pr}) · ${e.merged.slice(0, 10)} · ${e.summary}${closes}`;
};

const parts = [
  "# History",
  "",
  "What has landed, grouped by phase and then by topic. One line per merged PR: the PR, its merge",
  "date (UTC), what it gave us, and the issue it closed. The [build log](build-log/) has the full",
  "story of each change in date order; this page is the summary by topic.",
  "",
  "This page is generated by `npm run history` from [`docs/history/`](history/), one file per PR.",
  "Don't edit it by hand. It is regenerated now and then, so the newest PRs may be in that folder",
  "before they show up here.",
];

for (const phase of [...new Set(topics.map((t) => t.phase))]) {
  const inPhase = topics.filter((t) => t.phase === phase);
  const blocks = inPhase
    .map((t) => ({ t, rows: entries.filter((e) => e.phase === phase && e.topic === t.topic) }))
    .filter((b) => b.rows.length);
  if (!blocks.length) continue;
  parts.push("", `## ${phase}`);
  for (const { t, rows } of blocks) {
    parts.push("", `### ${t.topic}`, "", t.description, "", ...rows.map(line));
  }
}

// What's next is written by hand (docs/history/whats-next.md) and updated at weekly planning.
let next = `The open issues and their order are on the [project board](${board}).`;
try {
  next = readFileSync(join(dir, "whats-next.md"), "utf8").trim();
} catch {
  // no hand-written section: point at the board
}
parts.push("", "### What's next", "", next, "");
const text = parts.join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error(`${out} is out of date: run npm run history`);
    process.exit(1);
  }
  console.log(`${out} is up to date (${entries.length} PRs)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${entries.length} PRs)`);
}
