// Builds supabase/seed.sql from boat.json, so `npm run db:reset` loads the sample boat, its
// people, their memberships, its documents and procedures, and the boat's renewals, maintenance
// items and expenses into the local database. The hosted dev project loads the same file on every push to main, so the SQL
// is safe to re-run: existing rows are updated to match boat.json, never duplicated. Output is
// deterministic.
//
// The document files get into the private `documents` bucket through supabase/config.toml:
// `[storage.buckets.documents]` uploads supabase/storage/documents on `supabase start` and
// `supabase db reset`, and this script fills that folder with symlinks to the fixture PDFs at
// `<boat_id>/<name>.pdf`, the paths the document rows give.
// Run from the repo root: node fixtures/sample-boat/build-seed.mjs
import { mkdirSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const seedPath = join(here, "..", "..", "supabase", "seed.sql");
const storagePath = join(here, "..", "..", "supabase", "storage", "documents");
const { boat, people, memberships, documents, procedures, renewals, maintenance, expenses } = JSON.parse(
  readFileSync(join(here, "boat.json"), "utf8"),
);

// boat.json spells roles the way people say them; the database enum uses underscores.
const roles = { owner: "owner", "co-owner": "co_owner", crew: "crew", "read-only": "read_only" };

const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;
const sqlOrNull = (value) => (value === undefined ? "null" : sql(value));
const numOrNull = (value) => (value === undefined ? "null" : String(value));

// The auth provider's user ID is not Newton's person ID (docs/decisions/0001-auth.md), so each
// fixture person gets a separate, fixed auth ID: person ...0101 signs in as auth user ...0201.
const authId = (personId) => personId.replace(/01(\d\d)$/, "02$1");

// Each person signs in with their first verified sender address.
const loginEmail = (person) => person.verifiedSenders[0];

const documentFile = (document) => join(here, "documents", `${document.name}.pdf`);

// A record's `sourceDocument` names a document; the database links it by ID.
const documentId = (record) => {
  if (record.sourceDocument === undefined) return "null";
  const document = documents.find((d) => d.name === record.sourceDocument);
  if (!document) throw new Error(`Unknown sourceDocument in boat.json: ${record.sourceDocument}`);
  return sql(document.id);
};

// The part of the inbound address before the @. The domain is set per environment.
const emailAlias = boat.inboundAddress.split("@")[0];

const values = (rows) => rows.map((row) => `  (${row.join(", ")})`).join(",\n");

// On a re-run, rows that already exist take boat.json's values.
const upsert = (key, columns) =>
  `on conflict (${key.join(", ")}) do update set\n${columns.map((c) => `  ${c} = excluded.${c}`).join(",\n")}`;

const membershipRows = memberships.map((m) => {
  if (!roles[m.role]) throw new Error(`Unknown role in boat.json: ${m.role}`);
  return [sql(boat.id), sql(m.personId), `${sql(roles[m.role])}::public.membership_role`, String(m.ownershipPercent)];
});

const out = `-- Generated by fixtures/sample-boat/build-seed.mjs from fixtures/sample-boat/boat.json.
-- Don't edit by hand: change boat.json and run \`node fixtures/sample-boat/build-seed.mjs\`.
--
-- The made-up sample boat ${boat.name}, its people, their memberships, its documents and
-- procedures, and its renewals, maintenance items and expenses, so a fresh
-- \`npm run db:reset\` has a boat to sign in to. Sign in by magic link as any of these and read
-- the link in the local mail catcher at http://127.0.0.1:54324:
${people
  .map((p) => {
    const m = memberships.find((m) => m.personId === p.id);
    return `--   ${loginEmail(p).padEnd(20)} ${p.name}, ${m ? m.role : "not a member"}`;
  })
  .join("\n")}
--
-- The document rows point at files the Supabase CLI uploads from supabase/storage/documents
-- (see \`[storage.buckets.documents]\` in supabase/config.toml).
--
-- Safe to re-run (the hosted dev project loads it on every push to main): sign-in rows that
-- exist are left alone, and every other row is updated to match boat.json.

-- Auth users. The create_person_for_auth_user trigger gives each one a person. Token columns
-- are empty strings, not null, because Supabase Auth can't read nulls there.
insert into auth.users (
  instance_id, id, aud, role, email, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
) values
${values(
  people.map((p) => [
    "'00000000-0000-0000-0000-000000000000'",
    sql(authId(p.id)),
    "'authenticated'",
    "'authenticated'",
    sql(loginEmail(p)),
    "now()",
    `'{"provider": "email", "providers": ["email"]}'`,
    "'{}'",
    "now()",
    "now()",
    "''",
    "''",
    "''",
    "''",
  ]),
)}
on conflict do nothing;

-- The email identity magic-link sign-in looks up.
insert into auth.identities (
  id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at
) values
${values(
  people.map((p) => [
    sql(authId(p.id)),
    sql(authId(p.id)),
    sql(authId(p.id)),
    "'email'",
    `jsonb_build_object('sub', ${sql(authId(p.id))}, 'email', ${sql(loginEmail(p))}, 'email_verified', true)`,
    "now()",
    "now()",
    "now()",
  ]),
)}
on conflict do nothing;

-- Give the trigger-made people the fixture's IDs and names, so tests and demos can refer to them.
update public.people p
set id = f.id::uuid, display_name = f.name
from (values
${values(people.map((p) => [sql(p.id), sql(p.name), sql(authId(p.id))]))}
) as f (id, name, auth_subject)
where p.auth_subject = f.auth_subject
  and (p.id, p.display_name) is distinct from (f.id::uuid, f.name);

-- The boat's inbound address is its alias at the inbound domain: ${boat.inboundAddress}.
insert into public.boats (id, name, email_alias) values
${values([[sql(boat.id), sql(boat.name), sql(emailAlias)]])}
${upsert(["id"], ["name", "email_alias"])};

-- Every verified sender address after the first, which is the person's sign-in email.
insert into public.sender_addresses (person_id, address, verified_at) values
${values(
  people.flatMap((p) => p.verifiedSenders.slice(1).map((a) => [sql(p.id), sql(a.toLowerCase()), "now()"])),
)}
on conflict (address) do update set person_id = excluded.person_id, verified_at = coalesce(sender_addresses.verified_at, excluded.verified_at);

-- Ownership shares are the fixture's percentages; the cost split only uses their ratio.
insert into public.memberships (boat_id, person_id, role, ownership_share) values
${values(membershipRows)}
${upsert(["boat_id", "person_id"], ["role", "ownership_share"])};

-- Filed from the sample emails, so no person added them (email-in runs as a server job).
insert into public.documents (
  id, boat_id, storage_path, type, source, received_at, filename, content_type, size_bytes, added_by
) values
${values(
  documents.map((d) => [
    sql(d.id),
    sql(boat.id),
    sql(`${boat.id}/${d.name}.pdf`),
    `${sql(d.type)}::public.document_type`,
    `${sql(d.source)}::public.document_source`,
    sql(d.receivedAt),
    sql(`${d.name}.pdf`),
    "'application/pdf'",
    String(statSync(documentFile(d)).size),
    "null",
  ]),
)}
${upsert(["id"], ["boat_id", "storage_path", "type", "source", "received_at", "filename", "content_type", "size_bytes", "added_by"])};

insert into public.boat_procedures (id, boat_id, title, content) values
${values(procedures.map((p) => [sql(p.id), sql(boat.id), sql(p.title), sql(p.content)]))}
${upsert(["id"], ["boat_id", "title", "content"])};

insert into public.renewals (id, boat_id, kind, title, reference, expires_on, document_id) values
${values(
  renewals.map((r) => [
    sql(r.id),
    sql(boat.id),
    `${sql(r.kind)}::public.renewal_kind`,
    sql(r.title),
    sqlOrNull(r.reference),
    sql(r.expiresOn),
    documentId(r),
  ]),
)}
${upsert(["id"], ["boat_id", "kind", "title", "reference", "expires_on", "document_id"])};

insert into public.maintenance_items (
  id, boat_id, title, every_months, every_engine_hours, last_done_on, last_done_engine_hours, document_id
) values
${values(
  maintenance.map((m) => [
    sql(m.id),
    sql(boat.id),
    sql(m.title),
    numOrNull(m.everyMonths),
    numOrNull(m.everyEngineHours),
    sql(m.lastDoneOn),
    numOrNull(m.lastDoneEngineHours),
    documentId(m),
  ]),
)}
${upsert(["id"], ["boat_id", "title", "every_months", "every_engine_hours", "last_done_on", "last_done_engine_hours", "document_id"])};

insert into public.expenses (
  id, boat_id, description, amount_cents, currency, spent_on, paid_by, document_id
) values
${values(
  expenses.map((e) => {
    if (!Number.isSafeInteger(e.amountCents)) throw new Error(`Not whole cents in boat.json: ${e.amountCents}`);
    return [sql(e.id), sql(boat.id), sql(e.description), String(e.amountCents), sql(boat.currency), sql(e.spentOn), sql(e.paidBy), documentId(e)];
  }),
)}
${upsert(["id"], ["boat_id", "description", "amount_cents", "currency", "spent_on", "paid_by", "document_id"])};
`;

writeFileSync(seedPath, out);

// Relative symlinks, so the folder works in any checkout and the fixture PDFs stay the only copy.
rmSync(storagePath, { recursive: true, force: true });
mkdirSync(join(storagePath, boat.id), { recursive: true });
for (const d of documents) {
  const link = join(storagePath, boat.id, `${d.name}.pdf`);
  symlinkSync(relative(dirname(link), documentFile(d)), link);
}
