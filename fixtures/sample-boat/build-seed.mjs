// Builds supabase/seed.sql from boat.json, so `npm run db:reset` loads the sample boat, its
// people and their memberships into the local database. Output is deterministic.
// Run from the repo root: node fixtures/sample-boat/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const seedPath = join(here, "..", "..", "supabase", "seed.sql");
const { boat, people, memberships } = JSON.parse(readFileSync(join(here, "boat.json"), "utf8"));

// boat.json spells roles the way people say them; the database enum uses underscores.
const roles = { owner: "owner", "co-owner": "co_owner", crew: "crew", "read-only": "read_only" };

const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;

// The auth provider's user ID is not Newton's person ID (docs/decisions/0001-auth.md), so each
// fixture person gets a separate, fixed auth ID: person ...0101 signs in as auth user ...0201.
const authId = (personId) => personId.replace(/01(\d\d)$/, "02$1");

// Each person signs in with their first verified sender address.
const loginEmail = (person) => person.verifiedSenders[0];

const values = (rows) => rows.map((row) => `  (${row.join(", ")})`).join(",\n");

const membershipRows = memberships.map((m) => {
  if (!roles[m.role]) throw new Error(`Unknown role in boat.json: ${m.role}`);
  return [sql(boat.id), sql(m.personId), `${sql(roles[m.role])}::public.membership_role`];
});

const out = `-- Generated by fixtures/sample-boat/build-seed.mjs from fixtures/sample-boat/boat.json.
-- Don't edit by hand: change boat.json and run \`node fixtures/sample-boat/build-seed.mjs\`.
--
-- The made-up sample boat ${boat.name}, its people and their memberships, so a fresh
-- \`npm run db:reset\` has a boat to sign in to. Sign in by magic link as any of these and read
-- the link in the local mail catcher at http://127.0.0.1:54324:
${people
  .map((p) => {
    const m = memberships.find((m) => m.personId === p.id);
    return `--   ${loginEmail(p).padEnd(20)} ${p.name}, ${m ? m.role : "not a member"}`;
  })
  .join("\n")}
--
-- Ownership shares wait for the cost-split tables (#9).

-- Auth users. The create_person_for_auth_user trigger gives each one a person. Token columns
-- are empty strings, not null, because Supabase Auth can't read nulls there.
insert into auth.users (
  instance_id, id, aud, role, email, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
) values
${values(
  people.map((p) => [
    "'00000000-0000-0000-0000-000000000000'",
    sql(authId(p.id)),
    "'authenticated'",
    "'authenticated'",
    sql(loginEmail(p)),
    "now()",
    `'{"provider": "email", "providers": ["email"]}'`,
    "'{}'",
    "now()",
    "now()",
    "''",
    "''",
    "''",
    "''",
  ]),
)};

-- The email identity magic-link sign-in looks up.
insert into auth.identities (
  id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at
) values
${values(
  people.map((p) => [
    sql(authId(p.id)),
    sql(authId(p.id)),
    sql(authId(p.id)),
    "'email'",
    `jsonb_build_object('sub', ${sql(authId(p.id))}, 'email', ${sql(loginEmail(p))}, 'email_verified', true)`,
    "now()",
    "now()",
    "now()",
  ]),
)};

-- Give the trigger-made people the fixture's IDs and names, so tests and demos can refer to them.
update public.people p
set id = f.id::uuid, display_name = f.name
from (values
${values(people.map((p) => [sql(p.id), sql(p.name), sql(authId(p.id))]))}
) as f (id, name, auth_subject)
where p.auth_subject = f.auth_subject;

insert into public.boats (id, name) values
${values([[sql(boat.id), sql(boat.name)]])};

insert into public.memberships (boat_id, person_id, role) values
${values(membershipRows)};
`;

writeFileSync(seedPath, out);
